SRC_ROOT = ROOT / "src"
GUPKG_PY = SRC_ROOT / "gupkg" / "gupkg.py"
FIXTURES = ROOT / "tests" / "fixtures"


def load_gupkg_module():
    spec = importlib.util.spec_from_file_location("gupkg_under_test_cli", GUPKG_PY)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    try:
        spec.loader.exec_module(module)
    finally:
        sys.modules.pop(spec.name, None)
    return module


def runtime_module(name: str) -> ModuleType:
    """Return one runtime module loaded by the ``gupkg.py`` entrypoint."""

    return sys.modules[f"gupkg.{name}"]


@contextlib.contextmanager
def pushd(path: Path):
    cwd = Path.cwd()
    os.chdir(path)
    try:
        yield
    finally:
        os.chdir(cwd)


class GupkgCliBehaviorTests(unittest.TestCase):
    maxDiff = None

    def run_main(self, module, args: list[str]) -> tuple[int, str]:
        stdout = io.StringIO()
        with contextlib.redirect_stdout(stdout):
            try:
                code = module.main(args)
            except SystemExit as exc:
                code = exc.code
        if code is None:
            code = 0
        self.assertIsInstance(code, int)
        return code, stdout.getvalue()

    def user_env(self, tmpdir: str) -> dict[str, str]:
        root = Path(tmpdir)
        return {
            "APPDATA": str(root / "AppData"),
            "USERPROFILE": str(root / "UserProfile"),
        }

    def machine_env(self, tmpdir: str) -> dict[str, str]:
        root = Path(tmpdir)
        return {
            "PROGRAMDATA": str(root / "ProgramData"),
            "SYSTEMDRIVE": str(root / "SystemDrive"),
        }

    def copy_fixture(self, tmpdir: str, name: str) -> Path:
        destination = Path(tmpdir) / name
        shutil.copytree(FIXTURES / name, destination)
        return destination

    def make_version_dir(
        self, tmpdir: str, package: str, version_dir_name: str = "v1.0.0.l1"
    ) -> Path:
        version_dir = Path(tmpdir) / package / version_dir_name
        version_dir.mkdir(parents=True)
        return version_dir

    def write_config(self, version_dir: Path, text: str) -> None:
        version_dir.joinpath("pkg.toml").write_text(
            textwrap.dedent(text).lstrip(), encoding="utf-8"
        )

    def zip_bytes(self, entries: dict[str, str]) -> bytes:
        archive = io.BytesIO()
        with zipfile.ZipFile(archive, "w") as zip_file:
            for name, content in entries.items():
                zip_file.writestr(name, content)
        return archive.getvalue()

