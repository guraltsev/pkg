    def test_bootstrap_git_install_creates_populated_timestamped_version(self) -> None:
        """Installing bootstrap-git promotes its origin into an immutable version."""
        module = load_gupkg_module()

        with tempfile.TemporaryDirectory() as tmpdir:
            root = Path(tmpdir)
            upstream = root / "upstream"
            upstream.mkdir()

            # Build one upstream commit for the bootstrap template to resolve
            # without first populating the template's own App directory.
            self.run_git(upstream, "init")
            self.run_git(upstream, "checkout", "-b", "main")
            self.run_git(upstream, "config", "user.name", "Gupkg Tests")
            self.run_git(
                upstream, "config", "user.email", "gupkg-tests@example.invalid"
            )
            upstream.joinpath("payload.txt").write_text("one", encoding="utf-8")
            self.run_git(upstream, "add", "payload.txt")
            self.run_git(upstream, "commit", "-m", "initial")

            package_root = root / "ImmutableGitApp"
            version_dir = package_root / "vbootstrap-git.l2"
            version_dir.mkdir(parents=True)
            self.write_config(
                version_dir,
                f"""
                name = "ImmutableGitApp"
                version = "bootstrap-git"
                localVersion = 2

                [origin]
                mode = "git"
                url = "{upstream.as_posix()}"

                [update]

                [update.payload]
                mode = "git"
                """,
            )

            # Upgrade checks can inspect a bootstrap template directly without
            # populating App or requiring a current junction.
            check_code, check_output = self.run_main(
                module, ["--toml", "upgrade", "check", str(version_dir)]
            )
            self.assertEqual(check_code, module.EXIT_SUCCESS)
            self.assertIn("Available: v", check_output)
            self.assertIn('status = "available"', check_output)
            self.assertIn(
                "Upgrade is available. Run 'gupkg upgrade download' to stage it; "
                "this check did not change any files.",
                check_output,
            )
            self.assertNotIn("no changes needed", check_output)
            self.assertFalse((version_dir / "App").exists())

            # Installing the bootstrap template must stage and install a new
            # immutable .l1 version rather than activating bootstrap-git itself.
            with mock.patch.dict(os.environ, self.user_env(tmpdir), clear=False):
                with mock.patch.object(
                    module, "update_current_junction_if_needed", return_value=True
                ):
                    result = module.install_package(version_dir)

            new_versions = [
                path
                for path in package_root.glob("v*.l*")
                if path != version_dir
            ]
            self.assertTrue(result.ok, msg=result.errors)
            self.assertTrue(result.changed)
            self.assertEqual(len(new_versions), 1)

            new_version = new_versions[0]
            self.assertRegex(
                new_version.name,
                re.compile(r"^v\d{8}-\d{6}-git\.l1$"),
            )
            new_config = tomllib.loads(
                (new_version / "pkg.toml").read_text(encoding="utf-8")
            )
            self.assertEqual(new_config["name"], "ImmutableGitApp")
            self.assertEqual(
                new_config["version"], new_version.name[1:].rsplit(".l", 1)[0]
            )
            self.assertEqual(new_config["localVersion"], 1)
            self.assertEqual(new_config["update"]["payload"]["mode"], "git")
            self.assertEqual(
                (new_version / "App" / "payload.txt").read_text(encoding="utf-8"),
                "one",
            )
            self.assertTrue((new_version / "App" / ".git").is_dir())
            self.assertFalse((version_dir / "App").exists())

            # Reinstalling the same bootstrap must reuse its original .l1
            # promotion instead of creating an otherwise identical .l2.
            with mock.patch.dict(os.environ, self.user_env(tmpdir), clear=False):
                with mock.patch.object(
                    module, "update_current_junction_if_needed", return_value=True
                ):
                    repeat_result = module.install_package(version_dir)

            concrete_versions = [
                path for path in package_root.glob("v*.l*") if path != version_dir
            ]
            self.assertTrue(repeat_result.ok, msg=repeat_result.errors)
            self.assertEqual(concrete_versions, [new_version])
            self.assertTrue(new_version.name.endswith(".l1"))

            # A wrapper launched inside the active concrete version defaults
            # its path to ".". Accept that active version while retaining the
            # historical-version safety rule.
            upstream.joinpath("payload.txt").write_text("two", encoding="utf-8")
            self.run_git(upstream, "add", "payload.txt")
            self.run_git(upstream, "commit", "-m", "update")
            current = package_root / "current"
            current.mkdir()
            layout = runtime_module("layout")
            with mock.patch.dict(os.environ, self.user_env(tmpdir), clear=False):
                with mock.patch.object(layout, "is_junction", return_value=True):
                    with mock.patch.object(
                        layout, "get_junction_target", return_value=new_version
                    ):
                        with mock.patch.object(
                            module,
                            "update_current_junction_if_needed",
                            return_value=True,
                        ):
                            update_result = module.full_package_upgrade(
                                new_version, scope=module.Scope.USER
                            )

            updated_versions = [
                path
                for path in package_root.glob("v*.l*")
                if path not in {version_dir, new_version}
            ]
            self.assertTrue(update_result.ok, msg=update_result.errors)
            self.assertEqual(update_result.status, "installed-update")
            self.assertEqual(len(updated_versions), 1)
            self.assertEqual(
                (updated_versions[0] / "App" / "payload.txt").read_text(
                    encoding="utf-8"
                ),
                "two",
            )

